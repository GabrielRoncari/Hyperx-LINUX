"""udev rules and the supported-devices table, generated from the driver registry."""
from __future__ import annotations

import os

from . import APP_ID
from .catalog import is_firmware_mode
from .drivers import DRIVERS, Kind

RULES_PATH = "/etc/udev/rules.d/70-hyperx-linux.rules"
TRIGGER = "--action=change --subsystem-match=hidraw --subsystem-match=input --subsystem-match=misc"
GROUP = "hyperx"

# udev compares all ATTRS of a rule against one and the same parent device, but the interface number
# belongs to the USB interface and the ids to the USB device above it. So the interface number is
# copied into the environment first, and each device rule then matches ENV + ATTRS. Comments must be
# on their own lines: udev rejects anything after the last key.
HEADER = """\
# HyperX Linux: let the logged-in user talk to supported HyperX devices without root.
# Generated by `hyperx-linux udev-rules`; do not edit by hand.
# The number must stay below 73 so systemd's 73-seat-late.rules applies the uaccess tag.

ACTION=="remove", GOTO="hyperx_linux_end"
# Headset buttons given other actions: uinput passes the untouched buttons on and types the chosen keys
# (the same rule Steam ships); the headsets' own input devices are further below.
KERNEL=="uinput", SUBSYSTEM=="misc", {grant}, OPTIONS+="static_node=uinput"
SUBSYSTEM=="input", KERNEL=="event*", GOTO="hyperx_linux_input"
SUBSYSTEM!="hidraw", GOTO="hyperx_linux_end"
SUBSYSTEMS=="usb", ATTRS{{bInterfaceNumber}}=="?*", ENV{{HYPERX_LINUX_IF}}="$attr{{bInterfaceNumber}}"
"""
INPUT_HEADER = """\
GOTO="hyperx_linux_end"

# The input devices of the headsets: only their own buttons (media keys, mute)
LABEL="hyperx_linux_input"
"""
GROUP_NOTE = """\
# Without systemd-logind (eudev, elogind, mdev systems) uaccess does nothing, so access is granted
# to the "{group}" group instead: add your user to it and log in again.
"""
FOOTER = 'LABEL="hyperx_linux_end"\n'


def rules(group: str | None = None) -> str:
    """uaccess rules (systemd); with `group`, also GROUP/MODE for systems without uaccess."""
    grant = f'TAG+="uaccess", GROUP="{group}", MODE="0660"' if group else 'TAG+="uaccess"'
    lines = [HEADER.format(grant=grant)] + ([GROUP_NOTE.format(group=group)] if group else [])
    seen = set()
    for d in DRIVERS:
        lines.append(f"# {d.name} [{d.support.value}]")
        for vid, pid, variant in d.ids:
            if is_firmware_mode(vid, pid):
                continue  # bootloader ids are never granted
            for iface in (d.interfaces + d.extra_interfaces) if d.interfaces else (None,):
                if (vid, pid, iface) in seen:
                    continue
                seen.add((vid, pid, iface))
                match = f'ATTRS{{idVendor}}=="{vid:04x}", ATTRS{{idProduct}}=="{pid:04x}"'
                if iface is not None:
                    match = f'ENV{{HYPERX_LINUX_IF}}=="{iface:02x}", {match}'
                if variant:
                    lines.append(f"#   {variant}")
                lines.append(f"{match}, {grant}")
    lines.append(INPUT_HEADER)
    headsets = []
    for d in DRIVERS:
        for vid, pid, _variant in d.ids:
            if d.kind == Kind.HEADSET and not is_firmware_mode(vid, pid) and (vid, pid) not in headsets:
                headsets.append((vid, pid))
    lines += [f'ATTRS{{idVendor}}=="{vid:04x}", ATTRS{{idProduct}}=="{pid:04x}", {grant}' for vid, pid in headsets]
    lines += ["", FOOTER]
    return "\n".join(lines)


SEAT_LATE_RULES = ("/etc/udev/rules.d/73-seat-late.rules", "/usr/lib/udev/rules.d/73-seat-late.rules",
                   "/lib/udev/rules.d/73-seat-late.rules")


def uaccess_supported() -> bool:
    """TAG+="uaccess" needs a seat manager (logind, or elogind on eudev systems) and the rule that turns
    the tag into permissions (73-seat-late.rules, shipped by systemd and by elogind)."""
    if not os.path.isdir("/run/systemd/seats"):
        return False
    for path in SEAT_LATE_RULES:
        try:
            with open(path) as f:
                if "uaccess" in f.read():
                    return True
        except OSError:
            pass
    return False


def root_script() -> str:
    """sh script run as root (pkexec): rules from stdin; "$1" is the user to add to the group, if any."""
    install = (f"cat > {RULES_PATH}.new && mv {RULES_PATH}.new {RULES_PATH} && udevadm control --reload-rules "
               f"&& udevadm trigger {TRIGGER}")
    if uaccess_supported():
        return install
    return (f"{{ getent group {GROUP} >/dev/null || groupadd -r {GROUP} || addgroup -S {GROUP}; }} && "
            f"{{ usermod -aG {GROUP} \"$1\" || addgroup \"$1\" {GROUP}; }} && " + install)


def install_command(in_flatpak: bool) -> str:
    """Shell command that installs the rules; shown to users who prefer the terminal."""
    cmd = f"flatpak run {APP_ID} udev-rules" if in_flatpak else "hyperx-linux udev-rules"
    return (f"{cmd} | sudo tee {RULES_PATH} >/dev/null && sudo udevadm control --reload-rules "
            f"&& sudo udevadm trigger {TRIGGER}")


def outdated(group: str | None) -> bool:
    """Rules installed by an older version (new devices or features need the new ones)."""
    try:
        with open(RULES_PATH) as f:
            return f.read() != rules(group)
    except OSError:
        return False  # not installed: the permission page handles that


def supported_table(markdown: bool = False) -> str:
    rows = []
    for d in sorted(DRIVERS, key=lambda d: (d.kind.value, d.name)):
        ids = ", ".join(f"{vid:04x}:{pid:04x}" for vid, pid, _v in d.ids)
        features = ", ".join(c.cli_name for c in d.controls)
        rows.append((d.kind.value, d.name, ids, d.support.value, features))
    if not markdown:
        return "".join(f"{k:10} {n:40} {s:12} {i}\n    {f}\n" for k, n, i, s, f in rows)
    out = ["| Type | Device | USB IDs | Support | Features |", "|---|---|---|---|---|"]
    out += [f"| {k} | {n} | `{i}` | {s} | {f} |" for k, n, i, s, f in rows]
    return "\n".join(out) + "\n"


